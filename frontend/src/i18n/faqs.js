export function getFaqsForLang(arg1 = 'en', arg2 = 'home') {
  const LOCALES = ['en', 'es', 'ja', 'fr', 'de', 'pt', 'ko', 'it'];
  let lang = 'en';
  let category = 'home';

  if (LOCALES.includes(arg1)) {
    lang = arg1;
    category = arg2 || 'home';
  } else if (LOCALES.includes(arg2)) {
    lang = arg2;
    category = arg1 || 'home';
  } else {
    category = arg1 || 'home';
  }

  const langFaqs = FAQS_BY_LANG[lang] || FAQS_BY_LANG.en;
  return langFaqs[category] || langFaqs.home || FAQS_BY_LANG.en[category] || FAQS_BY_LANG.en.home;
}
